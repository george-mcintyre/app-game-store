export function icon(name: keyof typeof ICONS | string, cls = ""): Raw {
  const svg = ICONS[name] ?? ICONS.info;
  return raw(cls ? svg.replace("<svg ", `<svg class="${cls}" `) : svg);
}

export function appIcon(name: string, url: string | null | undefined, size: "xl" | "lg" | "md" | "sm" | "xs" = "md"): Raw {
  const fallback = iconUrl(name);
  return html`<img class="appicon ${size}" src="${url || fallback}" data-fallback="${fallback}" alt="" width="118" height="118" loading="lazy" />`;
}

export function avatar(name: string, url: string | null | undefined, size: "lg" | "" | "sm" = ""): Raw {
  const fallback = avatarUrl(name);
  return html`<img class="avatar ${size}" src="${url || fallback}" data-fallback="${fallback}" alt="" />`;
}

// Broken remote images fall back to the generated placeholder.
export function wireImages(root: ParentNode): void {
  root.querySelectorAll<HTMLImageElement>("img[data-fallback]").forEach((img) => {
    img.addEventListener("error", () => {
      if (img.src !== img.dataset.fallback) img.src = img.dataset.fallback!;
    }, { once: true });
  });
}

export function pill(text: string, tone: "" | "ok" | "warn" | "bad" | "accent" = "", dot = false): Raw {
  return html`<span class="pill ${tone}">${dot ? html`<i class="dot"></i>` : ""}${text}</span>`;
}

export function statePill(state: string): Raw {
  const label = state.replace(/-/g, " ");
  return html`<span class="pill state-${state}">${label}</span>`;
}

export function callout(kind: "info" | "warn" | "bad" | "ok", body: Raw | string, iconName?: string): Raw {
  return html`<div class="callout ${kind}">${icon(iconName ?? (kind === "ok" ? "check" : kind === "info" ? "info" : "warn"))}<div class="grow">${body}</div></div>`;
}

let toastTimer: number | undefined;
export function toast(message: string): void {
  let el = document.querySelector<HTMLElement>(".toast");
  if (!el) {
    el = document.createElement("div");
    el.className = "toast";
    document.body.appendChild(el);
  }
  el.textContent = message;
  el.classList.add("show");
  clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => el!.classList.remove("show"), 2200);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    toast("Copied");
    return true;
  } catch {
    toast("Could not copy");
    return false;
  }
}

export function copyRow(text: string, label = "Copy"): Raw {
  return html`<div class="copy-row"><code title="${text}">${text}</code><button type="button" class="btn secondary sm" data-copy="${text}">${icon("copy")} ${label}</button></div>`;
}

// Wire every [data-copy] button inside root.
export function wireCopy(root: ParentNode): void {
  root.querySelectorAll<HTMLButtonElement>("[data-copy]").forEach((b) => (b.onclick = () => void copyText(b.dataset.copy!)));
}

export function emptyState(iconName: string, title: string, body: string, cta?: Raw): Raw {
  return html`<div class="empty">${icon(iconName)}<h3>${title}</h3><p>${body}</p>${cta ?? ""}</div>`;
}

export function fmtDate(iso: string | null | undefined, withTime = false): string {
  if (!iso) return "";
  const d = new Date(iso);
  return withTime ? d.toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" }) : d.toLocaleDateString(undefined, { dateStyle: "medium" });
}

export function errorBox(err: unknown): Raw {
  return callout("bad", html`<p>${err instanceof Error ? err.message : String(err)}</p>`);
}
